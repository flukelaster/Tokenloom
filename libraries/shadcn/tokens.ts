import type { BrandPaletteShade, FigmaVariableScope, TokenDefinition } from '@schema';

const SOURCE_VER = '2.3.0';

function desc(
  enWhen: string,
  thWhen: string,
  enNot: string,
  thNot: string,
  enEx: string,
  thEx: string,
  enCon: string,
  thCon: string,
): TokenDefinition['description'] {
  return {
    whenToUse: { en: enWhen, th: thWhen },
    whenNotToUse: { en: enNot, th: thNot },
    example: { en: enEx, th: thEx },
    constraints: { en: enCon, th: thCon },
  };
}

function primColor(
  logicalId: string,
  name: string,
  sourceTokenName: string,
  hex: string,
  enRole: string,
  thRole: string,
  brandShade?: BrandPaletteShade,
): TokenDefinition {
  return {
    logicalId,
    collection: 'primitives',
    name,
    sourceTokenName,
    normalizedRole: logicalId,
    category: 'color',
    type: 'COLOR',
    valuesByMode: {
      Base: {
        kind: 'color',
        hex,
        ...(brandShade ? { brandShade } : {}),
      },
    },
    description: desc(
      `Raw palette step (${enRole}) referenced only by Semantic tokens.`,
      `ค่าสีพื้นฐาน (${thRole}) สำหรับให้อ้างอิงจาก Semantic tokens เท่านั้น`,
      'Do not bind directly onto UI components where Light/Dark theme switching is expected.',
      'ห้ามผูกกับ Component โดยตรงหากต้องการให้สลับโหมด Light/Dark อัตโนมัติ',
      `Aliased by semantic action or surface tokens (${name}).`,
      `ถูกอ้างอิงผ่าน Semantic token ของพื้นผิวหรือปุ่ม (${name})`,
      'Single Base mode in Primitives collection.',
      'อยู่ในคอลเลกชัน Primitives ที่มีเฉพาะ Base mode',
    ),
    scopes: ['ALL_FILLS', 'STROKE_COLOR', 'EFFECT_COLOR'],
    codeSyntax: { WEB: `var(--${name.replace(/\//g, '-')})` },
    expectedBindingTargets: ['semantic-alias'],
    sourceVersion: SOURCE_VER,
  };
}

function primFloat(
  logicalId: string,
  name: string,
  sourceTokenName: string,
  value: number,
  category: TokenDefinition['category'],
  scopes: FigmaVariableScope[],
  enLabel: string,
  thLabel: string,
  opts?: { radiusScaleFactor?: number; compactValue?: number },
): TokenDefinition {
  return {
    logicalId,
    collection: 'primitives',
    name,
    sourceTokenName,
    normalizedRole: logicalId,
    category,
    type: 'FLOAT',
    valuesByMode: {
      Base: {
        kind: 'float',
        value,
        ...(opts?.radiusScaleFactor !== undefined
          ? { radiusScaleFactor: opts.radiusScaleFactor }
          : {}),
        ...(opts?.compactValue !== undefined ? { compactValue: opts.compactValue } : {}),
      },
    },
    description: desc(
      `Scale value for ${enLabel} (${value}px default).`,
      `ค่าระดับสเกลสำหรับ${thLabel} (ค่าเริ่มต้น ${value}px)`,
      'Avoid arbitrary unaligned pixel values when a scale token fits.',
      'หลีกเลี่ยงการกำหนดตัวเลขพิกเซลเองโดยไม่ผ่านสเกลมาตรฐาน',
      `Used across layout spacing, sizing, or corner rounding (${name}).`,
      `ใช้กำหนดระยะห่าง ขนาด หรือความโค้งมุม (${name})`,
      'Non-negative numeric FLOAT variable.',
      'ตัวแปรตัวเลข FLOAT ที่มีค่าตั้งแต่ 0 ขึ้นไป',
    ),
    scopes,
    codeSyntax: { WEB: `var(--${name.replace(/\//g, '-')})` },
    expectedBindingTargets: ['AutoLayout', 'CornerRadius', 'Typography'],
    sourceVersion: SOURCE_VER,
  };
}

function semColorAlias(
  logicalId: string,
  name: string,
  sourceTokenName: string,
  normalizedRole: string,
  lightTargetId: string,
  darkTargetId: string,
  scopes: FigmaVariableScope[],
  enWhen: string,
  thWhen: string,
  enNot: string,
  thNot: string,
  enEx: string,
  thEx: string,
): TokenDefinition {
  return {
    logicalId,
    collection: 'semantic',
    name,
    sourceTokenName,
    normalizedRole,
    category: 'color',
    type: 'COLOR',
    valuesByMode: {
      Light: { kind: 'alias', targetLogicalId: lightTargetId },
      Dark: { kind: 'alias', targetLogicalId: darkTargetId },
    },
    description: desc(
      enWhen,
      thWhen,
      enNot,
      thNot,
      enEx,
      thEx,
      'Resolves dynamically via Light/Dark mode on parent Frame; verify WCAG contrast on custom brand overrides.',
      'เปลี่ยนค่าอัตโนมัติตามโหมด Light/Dark ของ Frame แม่ ควรตรวจค่า Contrast เมื่อปรับสีแบรนด์',
    ),
    scopes,
    codeSyntax: { WEB: `hsl(var(${sourceTokenName}))` },
    expectedBindingTargets: ['Frame.fills', 'TextNode.fills', 'Strokes'],
    sourceVersion: SOURCE_VER,
  };
}

function compAlias(
  logicalId: string,
  name: string,
  sourceTokenName: string,
  normalizedRole: string,
  category: TokenDefinition['category'],
  type: TokenDefinition['type'],
  targetLogicalId: string,
  scopes: FigmaVariableScope[],
  enWhen: string,
  thWhen: string,
  enEx: string,
  thEx: string,
): TokenDefinition {
  return {
    logicalId,
    collection: 'component',
    name,
    sourceTokenName,
    normalizedRole,
    category,
    type,
    valuesByMode: {
      Base: { kind: 'alias', targetLogicalId },
    },
    description: desc(
      enWhen,
      thWhen,
      'Do not repurpose this component-scoped token onto unrelated component families.',
      'ห้ามนำตัวแปรเฉพาะของ Component นี้ไปผูกกับ Component ตระกูลอื่นที่ไม่เกี่ยวข้อง',
      enEx,
      thEx,
      'Single Base mode that inherits Light/Dark resolution through its Semantic target.',
      'ใช้ Base mode เดียวและรับค่า Light/Dark ผ่าน Semantic token ที่อ้างอิงอยู่',
    ),
    scopes,
    codeSyntax: { WEB: `var(--${name.replace(/\//g, '-')})` },
    expectedBindingTargets: [name.split('/')[0]],
    sourceVersion: SOURCE_VER,
  };
}

